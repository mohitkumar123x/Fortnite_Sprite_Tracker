export type UiKey = keyof typeof ui.en;

export function localeFromPath(pathname: string): Locale {
  const seg = pathname.split('/').filter(Boolean)[0];
  if (seg === 'es' || seg === 'pt') return seg;
  return DEFAULT_LOCALE;
}

export function stripLocale(pathname: string): string {
  const stripped = pathname.replace(/^\/(es|pt)(?=\/|$)/, '');
  return stripped === '' ? '/' : stripped;
}

export function localizedPath(locale: Locale, path: string): string {
  const hashIndex = path.indexOf('#');
  const hash = hashIndex >= 0 ? path.slice(hashIndex) : '';
  const base = hashIndex >= 0 ? path.slice(0, hashIndex) : path;
  const clean = base.startsWith('/') ? base : `/${base}`;
  const normalized = clean === '' ? '/' : clean;
  if (locale === DEFAULT_LOCALE) return `${normalized}${hash}`;
  if (normalized === '/') return `/${locale}/${hash}`;
  return `/${locale}${normalized}${hash}`;
}

export function switchLocalePath(pathname: string, next: Locale): string {
  return localizedPath(next, stripLocale(pathname));
}

export function t(locale: Locale, key: UiKey, vars?: Record<string, string | number>): string {
  let value: string = ui[locale][key] ?? ui.en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replaceAll(`{${k}}`, String(v));
    }
  }
  return value;
}

